#!/usr/bin/env node
/**
 * 国际站静态构建：把 miniprogram/utils 的纯函数直接打成一个浏览器 bundle，
 * 再按 web/content 生成多语言页面、sitemap、robots。
 *
 * 设计约束（见 docs/14-intl-prd.md §12）：
 * - 不复制算法：只读取 miniprogram/utils 下的纯函数文件，避免第二份实现漂移。
 * - 零第三方依赖：不引 Astro/Vite，任何一台装了 Node 的机器都能构建。
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const OUT = path.join(ROOT, 'web', 'dist')
const CORE = ['time', 'format', 'sessions', 'plan']

const read = (rel) => fs.readFileSync(path.join(ROOT, rel), 'utf8')
const json = (rel) => JSON.parse(read(rel))

const site = json('web/content/site.json')
const i18n = json('web/content/i18n.json')
const { pages } = json('web/content/pages.json')

function esc(value) {
  return String(value == null ? '' : value)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
}

function bundleCore() {
  const defs = CORE.map((name) => {
    const src = read(`miniprogram/utils/${name}.js`)
    return `__def(${JSON.stringify(name)}, function (module, exports, require) {\n${src}\n});`
  }).join('\n')

  return `/* generated by tools/build-web.mjs */
(function () {
  var __reg = {};
  function __def(name, fn) { __reg[name] = { fn: fn, exports: {}, done: false }; }
  function __req(name) {
    var key = String(name).replace(/^\\.\\//, '').replace(/\\.js$/, '');
    var m = __reg[key];
    if (!m) throw new Error('core module not found: ' + name);
    if (!m.done) { m.fn(m, m.exports, __req); m.done = true; }
    return m.exports;
  }
${defs}
  window.SleepCore = {
    T: __req('time'),
    F: __req('format'),
    X: __req('sessions'),
    P: __req('plan')
  };
})();
`
}

function relativePrefix(slug) {
  const depth = slug.split('/').filter(Boolean).length
  return depth === 0 ? './' : '../'.repeat(depth)
}

function alternatesFor(page) {
  const links = []
  if (page.slug === '/' || page.slug === '/es/') {
    links.push({ lang: 'en', href: '/' })
    links.push({ lang: 'es', href: '/es/' })
    links.push({ lang: 'x-default', href: '/' })
  } else {
    links.push({ lang: page.locale, href: page.slug })
  }
  return links
}

function jsonLd(page, canonical) {
  const faq = (page.faq || []).map((item) => ({
    '@type': 'Question',
    name: item.q,
    acceptedAnswer: { '@type': 'Answer', text: item.a }
  }))
  const blocks = [
    {
      '@context': 'https://schema.org',
      '@type': 'WebApplication',
      name: page.h1,
      url: canonical,
      applicationCategory: 'HealthApplication',
      operatingSystem: 'Any',
      offers: { '@type': 'Offer', price: '0', priceCurrency: 'USD' }
    }
  ]
  if (faq.length) {
    blocks.push({ '@context': 'https://schema.org', '@type': 'FAQPage', mainEntity: faq })
  }
  return blocks
    .map((block) => `<script type="application/ld+json">${JSON.stringify(block)}</script>`)
    .join('\n    ')
}

function renderPage(page) {
  const t = i18n[page.locale]
  if (!t) throw new Error(`missing i18n for locale ${page.locale}`)
  const canonical = site.domain + (page.slug === '/' ? '/' : page.slug)
  const alts = alternatesFor(page)
    .map((a) => `<link rel="alternate" hreflang="${a.lang}" href="${site.domain}${a.href}" />`)
    .join('\n    ')
  const prefix = relativePrefix(page.slug)

  const faqHtml = (page.faq || [])
    .map(
      (item) => `<details class="faq"><summary>${esc(item.q)}</summary><p>${esc(item.a)}</p></details>`
    )
    .join('\n        ')

  const bullets = (page.bullets || []).map((b) => `<li>${esc(b)}</li>`).join('')

  return `<!doctype html>
<html lang="${esc(t.htmlLang)}">
  <head>
    <meta charset="utf-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1" />
    <title>${esc(page.title)}</title>
    <meta name="description" content="${esc(page.description)}" />
    <link rel="canonical" href="${canonical}" />
    ${alts}
    <meta property="og:type" content="website" />
    <meta property="og:title" content="${esc(page.title)}" />
    <meta property="og:description" content="${esc(page.description)}" />
    <meta property="og:url" content="${canonical}" />
    <meta name="twitter:card" content="summary" />
    <meta name="theme-color" content="${esc(site.themeColor)}" />
    <link rel="icon" href="${prefix}favicon.svg" type="image/svg+xml" />
    <link rel="stylesheet" href="${prefix}assets/app.css" />
    ${jsonLd(page, canonical)}
  </head>
  <body>
    <header class="top">
      <a class="brand" href="${page.locale === 'es' ? '/es/' : '/'}">${esc(site.brand)}</a>
      <nav class="nav">
        <a href="${page.locale === 'es' ? '/es/' : '/'}">${esc(t.calculate)}</a>
        <a href="${page.locale === 'es' ? '/es/a-que-hora-debo-dormir' : '/what-time-should-i-go-to-bed'}">${esc(t.modeWake)}</a>
      </nav>
    </header>

    <main>
      <h1>${esc(page.h1)}</h1>
      <p class="lead">${esc(page.lead)}</p>

      <section class="calc" id="calc" data-mode="${esc(page.mode)}" data-locale="${esc(page.locale)}">
        <div class="seg" role="tablist" aria-label="${esc(t.calculate)}">
          <button type="button" role="tab" data-mode="wake" class="is-on">${esc(t.modeWake)}</button>
          <button type="button" role="tab" data-mode="sleep">${esc(t.modeSleep)}</button>
        </div>

        <div class="row">
          <label for="clock" id="clock-label">${esc(t.shiftWake)}</label>
          <input id="clock" type="time" value="07:00" step="300" />
        </div>

        <div class="row">
          <label for="fall">${esc(t.fallLabel)}</label>
          <select id="fall">
            <option value="0">${esc(t.fallOptions['0'])}</option>
            <option value="10">${esc(t.fallOptions['10'])}</option>
            <option value="15" selected>${esc(t.fallOptions['15'])}</option>
            <option value="20">${esc(t.fallOptions['20'])}</option>
            <option value="30">${esc(t.fallOptions['30'])}</option>
          </select>
        </div>

        <p class="hint" id="result-head"></p>
        <ol class="slots" id="slots"></ol>

        <div class="actions">
          <button type="button" id="save" class="primary">${esc(t.save)}</button>
          <button type="button" id="share">${esc(t.share)}</button>
        </div>
        <p class="status" id="status" role="status"></p>
      </section>

      <ul class="bullets">${bullets}</ul>

      <section class="faqs">
        ${faqHtml}
      </section>

      <section class="saved">
        <h2>${esc(t.savedList)}</h2>
        <ul id="saved-list"></ul>
        <button type="button" id="clear">${esc(t.clearAll)}</button>
      </section>

      <p class="note">${esc(t.note)}</p>
      <p class="disclaimer"><strong>${esc(t.disclaimerLabel)}:</strong> ${esc(site.disclaimer)}</p>
    </main>

    <footer class="foot">
      <span>© ${new Date().getFullYear()} ${esc(site.brand)}</span>
      ${(site.footerLinks || [])
        .map((link) => `<a href="${esc(link.href)}">${esc(link.label)}</a>`)
        .join('')}
    </footer>

    <script>window.__PAGE__ = ${JSON.stringify({
      slug: page.slug,
      locale: page.locale,
      mode: page.mode,
      domain: site.domain
    })}; window.__I18N__ = ${JSON.stringify(t)}; window.__SITE__ = ${JSON.stringify({
      analyticsId: site.analyticsId || '',
      adsenseClient: site.adsenseClient || ''
    })};</script>
    <script src="${prefix}assets/core.js"></script>
    <script src="${prefix}assets/app.js"></script>
  </body>
</html>
`
}

function build() {
  fs.rmSync(OUT, { recursive: true, force: true })
  fs.mkdirSync(path.join(OUT, 'assets'), { recursive: true })

  fs.writeFileSync(path.join(OUT, 'assets', 'core.js'), bundleCore())
  fs.copyFileSync(path.join(ROOT, 'web', 'assets', 'app.js'), path.join(OUT, 'assets', 'app.js'))
  fs.copyFileSync(path.join(ROOT, 'web', 'assets', 'app.css'), path.join(OUT, 'assets', 'app.css'))
  fs.writeFileSync(path.join(OUT, 'favicon.svg'), FAVICON)

  const urls = []
  for (const page of pages) {
    const dir = page.slug === '/' ? OUT : path.join(OUT, page.slug.replace(/^\//, ''))
    fs.mkdirSync(dir, { recursive: true })
    fs.writeFileSync(path.join(dir, 'index.html'), renderPage(page))
    urls.push(site.domain + (page.slug === '/' ? '/' : page.slug))
  }

  fs.writeFileSync(
    path.join(OUT, 'sitemap.xml'),
    `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${urls.map((u) => `  <url><loc>${u}</loc></url>`).join('\n')}
</urlset>
`
  )
  fs.writeFileSync(
    path.join(OUT, 'robots.txt'),
    `User-agent: *\nAllow: /\nSitemap: ${site.domain}/sitemap.xml\n`
  )
  fs.writeFileSync(
    path.join(OUT, '404.html'),
    `<!doctype html><html lang="en"><head><meta charset="utf-8"><title>Not found</title>
<link rel="stylesheet" href="/assets/app.css"></head>
<body><main><h1>Page not found</h1><p><a href="/">Back to the sleep calculator</a></p></main></body></html>`
  )
  // Cloudflare Pages：安全头 + 静态资源长缓存 + HTML 短缓存
  fs.writeFileSync(
    path.join(OUT, '_headers'),
    `/*
  X-Content-Type-Options: nosniff
  Referrer-Policy: no-referrer
  X-Frame-Options: DENY
  Permissions-Policy: camera=(), microphone=(), geolocation=()
  Content-Security-Policy: default-src 'self'; img-src 'self' data:; style-src 'self'; script-src 'self' 'unsafe-inline'; connect-src 'self' https:; base-uri 'none'; form-action 'none'; frame-ancestors 'none'

/assets/*
  Cache-Control: public, max-age=31536000, immutable

/*.html
  Cache-Control: public, max-age=300, must-revalidate
`
  )

  console.log(`[web] built ${pages.length} pages -> ${path.relative(ROOT, OUT)}`)
}

const FAVICON = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 32 32"><rect width="32" height="32" rx="8" fill="#0b1020"/><path d="M20.5 8.5a8 8 0 1 0 3 11.8 6.4 6.4 0 0 1-3-11.8z" fill="#fde68a"/></svg>`

build()
